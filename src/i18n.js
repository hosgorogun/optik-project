export function createT(lang) {
  return (key, vars = {}) => {
    const table = translations[lang] || translations.TR;
    let text = table[key] ?? translations.TR[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replaceAll(`{${k}}`, String(v));
    });
    return text;
  };
}
